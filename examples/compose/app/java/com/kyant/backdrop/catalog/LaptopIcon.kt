/** Estado del icono LaptopIcon: expone el control imperativo usado por el catálogo. */
class LaptopIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberLaptopIconState(): LaptopIconState = remember { LaptopIconState() }

private val LaptopIconShapes: List<LucideShape> =
    listOf(
        LucideShape(lucidePath("M4 15.526 V7 A2 2 0 0 1 6 5 H18 A2 2 0 0 1 20 7 V15.526"), LucideMotion(12.0f, 12.0f, mapOf("rotateX" to lucideTrack(floatArrayOf(0f, 72.0f, -6.0f, 2.0f, 0f), floatArrayOf(0f, 0.2f, 0.7f, 0.88f, 1.0f), 1.4f, 0f, LucideEase.InOut))), false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(lucidePath("M20 15.526 A2 2 0 0 0 20.212 16.423 L21.28 18.55 A1 1 0 0 1 20.38 20 H3.62 A1 1 0 0 1 2.72 18.55 L3.788 16.423 A2 2 0 0 0 4 15.526"), null, false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(lucidePath("M20.054 15.987 H3.946"), null, false, true, 1.0f, 2.0f, null, 0f)
    )

private const val LaptopIconTotalSeconds: Float = 1.4000f

/** Conversión a Compose del icono animado `laptop` de animateicons/Lucide. */
@Composable
fun LaptopIcon(
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    color: Color = Color.Unspecified,
    isAnimated: Boolean = true,
    duration: Float = 1f,
    state: LaptopIconState? = null,
) {
    val interactionSource = remember { MutableInteractionSource() }
    val isHovered by interactionSource.collectIsHoveredAsState()
    val phase = remember { Animatable(0f) }
    val scope = rememberCoroutineScope()
    val motionScale = scope.coroutineContext[MotionDurationScale]?.scaleFactor ?: 1f

    var animationJob by remember { mutableStateOf<Job?>(null) }

    val start: () -> Unit =
        remember(motionScale, duration) {
            {
                if (motionScale <= 0f) {
                    state?.onAnimationEnd?.invoke()
                    return@remember
                }
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                        phase.animateTo(
                            targetValue = 1f,
                            animationSpec =
                                tween(
                                    durationMillis = (1400 * duration.coerceAtLeast(0.1f)).toInt(),
                                ),
                        )
                        phase.snapTo(0f)
                        // animateTo vuelve aquí solo si no se canceló: fin de la animación.
                        state?.onAnimationEnd?.invoke()
                    }
            }
        }

    val stop: () -> Unit =
        remember {
            {
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                    }
            }
        }

    // start/stop como claves: al cambiar `duration` se recalculan y hay que
    // re-registrarlos en el State, o el action seguiría usando la duración vieja.
    DisposableEffect(state, start, stop) {
        if (state != null) {
            state.startAction = start
            state.stopAction = stop
        }
        onDispose {
            if (state != null) {
                state.startAction = null
                state.stopAction = null
                state.onAnimationEnd = null
            }
            animationJob?.cancel()
            animationJob = null
        }
    }

    LaunchedEffect(isHovered, isAnimated) {
        if (isAnimated && isHovered) {
            start()
        } else {
            stop()
        }
    }

    val resolvedColor =
        remember(color) {
            if (color == Color.Unspecified) Color(0xFF00BCD4) else color
        }

    Canvas(
        modifier =
            modifier
                .size(size)
                .hoverable(
                    interactionSource = interactionSource,
                    enabled = isAnimated,
                ),
    ) {
        val seconds = phase.value * LaptopIconTotalSeconds * duration.coerceAtLeast(0.1f)
        scale(this.size.width / 24f, this.size.height / 24f, pivot = Offset.Zero) {
            drawLucideNodes(LaptopIconShapes, seconds, resolvedColor)
        }
    }
}
