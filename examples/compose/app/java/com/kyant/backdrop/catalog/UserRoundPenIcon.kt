/** Estado del icono UserRoundPenIcon: expone el control imperativo usado por el catálogo. */
class UserRoundPenIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberUserRoundPenIconState(): UserRoundPenIconState = remember { UserRoundPenIconState() }

