/** Estado del icono MicVocalIcon: expone el control imperativo usado por el catálogo. */
class MicVocalIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberMicVocalIconState(): MicVocalIconState = remember { MicVocalIconState() }

private val MicVocalIconShapes: List<LucideShape> =
    listOf(
