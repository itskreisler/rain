/** Estado del icono BicepsFlexedIcon: expone el control imperativo usado por el catálogo. */
class BicepsFlexedIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberBicepsFlexedIconState(): BicepsFlexedIconState = remember { BicepsFlexedIconState() }

private val BicepsFlexedIconShapes: List<LucideShape> =
    listOf(
        LucideShape(lucidePath("M12.409 13.017 A5 5 0 0 1 22 15 C22 18.866 18 22 13 22 C8.923 22 4.847 21.18 2.629 19.538 C2.203 19.222 1.998 18.706 2.009 18.176 C2.118 12.723 2.627 2 10 2 A3 3 0 0 1 13 5 A2 2 0 0 1 11 7 C9.895 7 9.36 6.556 9 6"), null, false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(lucidePath("M15 14 A5 5 0 0 0 7.416 16"), null, false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(lucidePath("M9.964 6.825 C8.019 7.977 9.5 13 8 15"), null, false, true, 1.0f, 2.0f, null, 0f)
    )

private const val BicepsFlexedIconTotalSeconds: Float = 0.6000f

/** Conversión a Compose del icono animado `biceps-flexed` de animateicons/Lucide. */
@Composable
fun BicepsFlexedIcon(
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    color: Color = Color.Unspecified,
    isAnimated: Boolean = true,
    duration: Float = 1f,
    state: BicepsFlexedIconState? = null,
) {
    val interactionSource = remember { MutableInteractionSource() }
    val isHovered by interactionSource.collectIsHoveredAsState()
    val phase = remember { Animatable(0f) }
    val scope = rememberCoroutineScope()
    val motionScale = scope.coroutineContext[MotionDurationScale]?.scaleFactor ?: 1f

    var animationJob by remember { mutableStateOf<Job?>(null) }

    val start: () -> Unit =
        remember(motionScale, duration) {
            {
                if (motionScale <= 0f) {
                    state?.onAnimationEnd?.invoke()
                    return@remember
                }
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                        phase.animateTo(
                            targetValue = 1f,
                            animationSpec =
                                tween(
                                    durationMillis = (600 * duration.coerceAtLeast(0.1f)).toInt(),
                                ),
                        )
                        phase.snapTo(0f)
                        // animateTo vuelve aquí solo si no se canceló: fin de la animación.
                        state?.onAnimationEnd?.invoke()
                    }
            }
        }

    val stop: () -> Unit =
        remember {
            {
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                    }
            }
        }

    // start/stop como claves: al cambiar `duration` se recalculan y hay que
    // re-registrarlos en el State, o el action seguiría usando la duración vieja.
    DisposableEffect(state, start, stop) {
        if (state != null) {
            state.startAction = start
            state.stopAction = stop
        }
        onDispose {
            if (state != null) {
                state.startAction = null
                state.stopAction = null
                state.onAnimationEnd = null
            }
            animationJob?.cancel()
            animationJob = null
        }
    }

    LaunchedEffect(isHovered, isAnimated) {
        if (isAnimated && isHovered) {
            start()
        } else {
            stop()
        }
    }

    val resolvedColor =
        remember(color) {
            if (color == Color.Unspecified) Color(0xFF4CAF50) else color
        }

    Canvas(
        modifier =
            modifier
                .size(size)
                .hoverable(
                    interactionSource = interactionSource,
                    enabled = isAnimated,
                ),
    ) {
        val seconds = phase.value * BicepsFlexedIconTotalSeconds * duration.coerceAtLeast(0.1f)
        scale(this.size.width / 24f, this.size.height / 24f, pivot = Offset.Zero) {
            drawLucideNodes(BicepsFlexedIconShapes, seconds, resolvedColor)
        }
    }
}
