/** Estado del icono MapIcon: expone el control imperativo usado por el catálogo. */
class MapIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberMapIconState(): MapIconState = remember { MapIconState() }

private val MapIconShapes: List<LucideShape> =
    listOf(
