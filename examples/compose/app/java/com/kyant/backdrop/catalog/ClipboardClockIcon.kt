/** Estado del icono ClipboardClockIcon: expone el control imperativo usado por el catálogo. */
class ClipboardClockIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberClipboardClockIconState(): ClipboardClockIconState = remember { ClipboardClockIconState() }

private val ClipboardClockIconShapes: List<LucideShape> =
    listOf(
