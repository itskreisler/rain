/** Estado del icono DoorOpenIcon: expone el control imperativo usado por el catálogo. */
class DoorOpenIconState internal constructor() {
    internal var startAction: (() -> Unit)? = null
    internal var stopAction: (() -> Unit)? = null

    /** Se ejecuta cuando la animación termina sin haberse cancelado. */
    var onAnimationEnd: (() -> Unit)? = null

    fun startAnimation() {
        startAction?.invoke()
    }

    fun stopAnimation() {
        stopAction?.invoke()
    }
}

@Composable
fun rememberDoorOpenIconState(): DoorOpenIconState = remember { DoorOpenIconState() }

private val DoorOpenIconShapes: List<LucideShape> =
    listOf(
        LucideShape(lucidePath("M11 20 H2"), null, false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(null, LucideMotion(11.0f, 12.0f, mapOf("scaleX" to lucideTrack(floatArrayOf(1.0f, 0.35f, 1.05f, 1.0f), floatArrayOf(0f, 0.4f, 0.75f, 1.0f), 0.7f, 0f, LucideEase.InOut))), false, true, 1.0f, 2.0f, null, 0f, listOf(LucideShape(lucidePath("M11 4.562 V20.719 A1 1 0 0 0 12.242 21.689 L19 20 V5.562 A2 2 0 0 0 17.485 3.622 L13.485 2.622 A2 2 0 0 0 11 4.561 Z"), null, false, true, 1.0f, 2.0f, null, 0f), LucideShape(lucidePath("M14 12 H14.01"), null, false, true, 1.0f, 2.0f, null, 0f))),
        LucideShape(lucidePath("M11 4 H8 A2 2 0 0 0 6 6 V20"), null, false, true, 1.0f, 2.0f, null, 0f),
        LucideShape(lucidePath("M22 20 H19"), null, false, true, 1.0f, 2.0f, null, 0f)
    )

private const val DoorOpenIconTotalSeconds: Float = 0.7000f

/** Conversión a Compose del icono animado `door-open` de animateicons/Lucide. */
@Composable
fun DoorOpenIcon(
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    color: Color = Color.Unspecified,
    isAnimated: Boolean = true,
    duration: Float = 1f,
    state: DoorOpenIconState? = null,
) {
    val interactionSource = remember { MutableInteractionSource() }
    val isHovered by interactionSource.collectIsHoveredAsState()
    val phase = remember { Animatable(0f) }
    val scope = rememberCoroutineScope()
    val motionScale = scope.coroutineContext[MotionDurationScale]?.scaleFactor ?: 1f

    var animationJob by remember { mutableStateOf<Job?>(null) }

    val start: () -> Unit =
        remember(motionScale, duration) {
            {
                if (motionScale <= 0f) {
                    state?.onAnimationEnd?.invoke()
                    return@remember
                }
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                        phase.animateTo(
                            targetValue = 1f,
                            animationSpec =
                                tween(
                                    durationMillis = (700 * duration.coerceAtLeast(0.1f)).toInt(),
                                ),
                        )
                        phase.snapTo(0f)
                        // animateTo vuelve aquí solo si no se canceló: fin de la animación.
                        state?.onAnimationEnd?.invoke()
                    }
            }
        }

    val stop: () -> Unit =
        remember {
            {
                animationJob?.cancel()
                animationJob =
                    scope.launch {
                        phase.snapTo(0f)
                    }
            }
        }

    // start/stop como claves: al cambiar `duration` se recalculan y hay que
    // re-registrarlos en el State, o el action seguiría usando la duración vieja.
    DisposableEffect(state, start, stop) {
        if (state != null) {
            state.startAction = start
            state.stopAction = stop
        }
        onDispose {
            if (state != null) {
                state.startAction = null
                state.stopAction = null
                state.onAnimationEnd = null
            }
            animationJob?.cancel()
            animationJob = null
        }
    }

    LaunchedEffect(isHovered, isAnimated) {
        if (isAnimated && isHovered) {
            start()
        } else {
            stop()
        }
    }

    val resolvedColor =
        remember(color) {
            if (color == Color.Unspecified) Color(0xFF2196F3) else color
        }

    Canvas(
        modifier =
            modifier
                .size(size)
                .hoverable(
                    interactionSource = interactionSource,
                    enabled = isAnimated,
                ),
    ) {
        val seconds = phase.value * DoorOpenIconTotalSeconds * duration.coerceAtLeast(0.1f)
        scale(this.size.width / 24f, this.size.height / 24f, pivot = Offset.Zero) {
            drawLucideNodes(DoorOpenIconShapes, seconds, resolvedColor)
        }
    }
}
